import { configDotenv } from "dotenv";
configDotenv();

const requiredEnv = [
  "PORT",
  "NODE_ENV",
  "CROSS_SITE",
  "FRONTEND_URL",
  "MONGODB_URL",
  "MAX_FILE_SIZE",
  "JWT_ACCESS_SECRET",
  "JWT_REFRESH_SECRET",
  "JWT_ACCESS_EXPIRATION",
  "JWT_REFRESH_EXPIRATION",
  "CSRF_SECRET",
  "CLOUDINARY_API_KEY",
  "CLOUDINARY_API_SECRET",
  "CLOUDINARY_CLOUD_NAME",
  "SHOCARTY_PROFILE",
  "SHOCARTY_PRODUCT",
  "SHOCARTY_ORDER",
  "MAIL_HOST",
  "MAIL_PORT",
  "MAIL_FROM_NAME",
  "RAZORPAY_KEY",
  "RAZORPAY_SECRET",
  "AUTH_LIMIT_WINDOW",
  "AUTH_LIMIT_MAX",
  "NORMAL_WINDOW",
  "NORMAL_MAX",
  "SEARCH_WINDOW",
  "SEARCH_MAX",
];

requiredEnv.forEach((key) => {
  if (!process.env[key]) {
    console.error(`Missing environment variable: ${key}`);
    process.exit(1);
  }
});

